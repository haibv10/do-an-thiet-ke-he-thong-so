#!/usr/bin/env python3
"""Generate compact 1-bit pixel masks from Lato fonts and Lucide SVGs.

Regeneration only: Pillow, python3-gi, python3-cairo, gir1.2-rsvg-2.0,
and fonts-lato. Normal firmware builds use the committed generated assets.
"""
import argparse
import io
import shutil
import subprocess
from pathlib import Path
from PIL import Image, ImageFont
import gi
import cairo
gi.require_version("Rsvg", "2.0")
from gi.repository import Rsvg

ROOT = Path(__file__).resolve().parents[1]
FACES = [
    ("TINY", 5, "Bold", "".join(sorted(set("WAITING FOR SENSORS ADC OFFLINE DHT11 RTC NEEDS SET GAS ABOVE THRESHOLD ALL SENSORS ONLINE 0123456789-")))),
    ("LABEL", 6, "Bold", "".join(sorted(set("TEMP HUMID GAS / MQ-5 CLEAN WARN DANGER NO ADC LIVE MIN MAX")))),
    ("TITLE", 7, "Bold", "".join(sorted(set("ENV MONITOR GAS HISTORY")))),
    ("BODY", 7, "Bold", "ABCDEFGHIJKLMNOPRSTUVWY0123456789 /-,:mVC%"),
    ("SECONDS", 15, "Bold", "0123456789:-"),
    ("VALUE", 17, "Bold", "0123456789-"),
    ("SENSOR", 22, "Bold", "0123456789-"),
    ("CLOCK", 27, "Bold", "0123456789:-"),
]


# Native 3x5 glyphs keep small labels legible without fractional coverage.
PIXEL_ROWS = {
    "A": "010/101/111/101/101", "B": "110/101/110/101/110",
    "C": "011/100/100/100/011", "D": "110/101/101/101/110",
    "E": "111/100/110/100/111", "F": "111/100/110/100/100",
    "G": "011/100/101/101/011", "H": "101/101/111/101/101",
    "I": "111/010/010/010/111", "J": "001/001/001/101/010",
    "K": "101/101/110/101/101", "L": "100/100/100/100/111",
    "M": "101/111/111/101/101", "N": "101/111/111/111/101",
    "O": "010/101/101/101/010", "P": "110/101/110/100/100",
    "Q": "010/101/101/111/011", "R": "110/101/110/101/101",
    "S": "011/100/010/001/110", "T": "111/010/010/010/010",
    "U": "101/101/101/101/111", "V": "101/101/101/101/010",
    "W": "101/101/111/111/101", "X": "101/101/010/101/101",
    "Y": "101/101/010/010/010", "Z": "111/001/010/100/111",
    "0": "111/101/101/101/111", "1": "010/110/010/010/111",
    "2": "110/001/010/100/111", "3": "110/001/010/001/110",
    "4": "101/101/111/001/001", "5": "111/100/110/001/110",
    "6": "011/100/111/101/111", "7": "111/001/010/010/010",
    "8": "111/101/111/101/111", "9": "111/101/111/001/110",
    " ": "000/000/000/000/000", "-": "000/000/111/000/000",
    "/": "001/001/010/100/100", ":": "000/010/000/010/000",
    ",": "000/000/000/010/100", "%": "101/001/010/100/101",
}


def pack(image):
    data = []
    value = bits = 0
    for pixel in image.tobytes():
        level = 1 if pixel >= 96 else 0
        value = (value << 1) | level
        bits += 1
        if bits == 8:
            data.append(value)
            value = bits = 0
    if bits:
        data.append(value << (8 - bits))
    return data


def array(name, data):
    rows = [", ".join(f"0x{x:02x}" for x in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path, default=Path("/usr/share/fonts/truetype/lato"))
    args = parser.parse_args()
    header = '''/* Generated by tools/generate_ui_assets.py. See graphics/licenses/. */
#ifndef UI_ASSETS_H
#define UI_ASSETS_H
struct ui_glyph {
  unsigned short offset;
  unsigned char width, height, advance;
  signed char top;
  /* advance bit 7 encodes a left bearing of -1; low bits hold the advance. */
};
struct ui_font {
  const char *characters;
  const struct ui_glyph *glyphs;
  const unsigned char *pixels;
  unsigned char cap_height;
};
struct ui_icon { const unsigned char *pixels; unsigned char width, height; };
'''
    code = ['/* Generated 1-bit pixel masks. See licenses/Lato.txt and licenses/Lucide.txt. */\n#include "ui_assets.h"\n']
    for name, size, weight, characters in FACES:
        font = ImageFont.truetype(str(args.font_dir / f"Lato-{weight}.ttf"), size)
        data, metrics = [], []
        for char in characters:
            left, top, right, bottom = font.getbbox(char, anchor="ls")
            width, height = right - left, bottom - top
            im = Image.new("L", (width, height))
            from PIL import ImageDraw
            draw = ImageDraw.Draw(im)
            # FreeType monochrome hinting aligns strokes to the native TFT grid.
            draw.fontmode = "1"
            draw.text((-left, -top), char, font=font, fill=255, anchor="ls")
            if size <= 7:
                im = Image.new("L", (3, 5))
                for y, row in enumerate(PIXEL_ROWS[char.upper()].split("/")):
                    for x, bit in enumerate(row):
                        im.putpixel((x, y), 255 if bit == "1" else 0)
                left, top, width, height = 0, -5, 3, 5
            advance = 4 if size <= 7 else round(font.getlength(char))
            if left not in (0, -1):
                raise ValueError(f"unsupported left bearing for {char}: {left}")
            metrics.append((len(data), width, height, advance | (128 if left == -1 else 0), top))
            data.extend(pack(im))
        ident = name.lower()
        code.append(array(f"{ident}_pixels", data))
        code.append(f"static const struct ui_glyph {ident}_glyphs[] = {{\n" +
                    ",\n".join("  {" + ", ".join(map(str, row)) + "}" for row in metrics) + "\n};\n")
        cap_height = 5 if size <= 7 else -font.getbbox("H", anchor="ls")[1]
        code.append(f'const struct ui_font ui_{ident} = {{"{characters}", {ident}_glyphs, {ident}_pixels, {cap_height}}};\n')
        header += f"extern const struct ui_font ui_{ident};\n"
    for name in ("thermometer", "droplets", "wind", "activity"):
        svg = (ROOT / "sw/graphics/icons" / f"{name}.svg").read_text().replace("currentColor", "#ffffff")
        handle = Rsvg.Handle.new_from_data(svg.encode())
        surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, 48, 48)
        viewport = Rsvg.Rectangle()
        viewport.x = viewport.y = 0
        viewport.width = viewport.height = 48
        handle.render_document(cairo.Context(surface), viewport)
        stream = io.BytesIO()
        surface.write_to_png(stream)
        stream.seek(0)
        image = Image.open(stream).getchannel("A").resize((12, 12), Image.Resampling.LANCZOS)
        code.append(array(name + "_pixels", pack(image)))
        code.append(f"const struct ui_icon ui_{name} = {{{name}_pixels, 12, 12}};\n")
        header += f"extern const struct ui_icon ui_{name};\n"
    (ROOT / "sw/graphics/ui_assets.h").write_text(header + "#endif\n")
    (ROOT / "sw/graphics/ui_assets.c").write_text("\n".join(code))
    if shutil.which("clang-format"):
        style = ("{BasedOnStyle: LLVM, IndentWidth: 2, ContinuationIndentWidth: 4, "
                 "ColumnLimit: 100, SortIncludes: Never}")
        subprocess.run(["clang-format", "-i", "--style=" + style,
                        str(ROOT / "sw/graphics/ui_assets.c"),
                        str(ROOT / "sw/graphics/ui_assets.h")], check=True)


if __name__ == "__main__":
    main()
